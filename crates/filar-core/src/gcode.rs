//! G-code post-processor.
//!
//! Takes a [`Plan`] and writes it out for the project's machine profile. Each
//! plan sample becomes one linear move, so the file is exactly what the
//! simulation shows.
//!
//! Feed rates are computed from the numbers actually printed (after
//! rounding), so a controller that derives move time from distance and `F`
//! arrives at the same duration the planner intended.

use std::fmt::Write;

use serde::Serialize;

use crate::machine::{Axis, CommentStyle, FeedMode, RotaryMode};
use crate::plan::{BlockKind, Plan};
use crate::project::{LayerKind, Project};

#[derive(Serialize, Clone, Debug, Default)]
#[serde(rename_all = "camelCase")]
pub struct Gcode {
    pub text: String,
    pub lines: usize,
    pub moves: usize,
    /// Planned run time (s).
    pub duration: f64,
    /// For every line of `text`: program time (s) when that line completes.
    /// Lets a viewer follow along with the simulation.
    pub line_times: Vec<f32>,
}

struct Writer {
    text: String,
    times: Vec<f32>,
    style: CommentStyle,
    numbered: bool,
    n: usize,
    now: f64,
}

impl Writer {
    fn raw(&mut self, line: &str) {
        self.text.push_str(line);
        self.text.push('\n');
        self.times.push(self.now as f32);
    }
    fn code(&mut self, line: &str) {
        if self.numbered {
            self.n += 1;
            let numbered = format!("N{} {}", self.n, line);
            self.raw(&numbered);
        } else {
            self.raw(line);
        }
    }
    fn comment(&mut self, text: &str) {
        match self.style {
            CommentStyle::Semicolon => self.raw(&format!("; {text}")),
            CommentStyle::Parentheses => {
                let clean: String =
                    text.chars().map(|c| if c == '(' || c == ')' { ' ' } else { c }).collect();
                self.raw(&format!("({clean})"));
            }
            CommentStyle::None => {}
        }
    }
    fn verbatim(&mut self, block: &str) {
        for line in block.lines() {
            let line = line.trim_end();
            if !line.is_empty() {
                self.code(line);
            }
        }
    }
}

/// Format with a fixed number of decimals, then drop trailing zeros.
fn num(v: f64, decimals: u8) -> String {
    let mut s = format!("{:.*}", decimals as usize, v);
    if s.contains('.') {
        while s.ends_with('0') {
            s.pop();
        }
        if s.ends_with('.') {
            s.pop();
        }
    }
    if s == "-0" {
        s = "0".into();
    }
    s
}

fn quantise(v: f64, decimals: u8) -> f64 {
    let k = 10f64.powi(decimals as i32);
    (v * k).round() / k
}

fn fmt_duration(s: f64) -> String {
    let s = s.round() as u64;
    if s >= 3600 {
        format!("{}h {:02}m {:02}s", s / 3600, (s % 3600) / 60, s % 60)
    } else {
        format!("{}m {:02}s", s / 60, s % 60)
    }
}

pub fn generate(project: &Project, plan: &Plan) -> Gcode {
    let m = &project.machine;
    let g = &m.gcode;
    let dec = g.decimals.min(6);
    let mut w = Writer {
        text: String::new(),
        times: Vec::new(),
        style: g.comments,
        numbered: g.line_numbers,
        n: 0,
        now: 0.0,
    };

    // Axes in output order: carriage, spindle, cross-feed, eye.
    let axes: [&Axis; 4] = [&m.carriage, &m.spindle, &m.crossfeed, &m.eye];
    let is_linear = [true, false, true, false];
    const SPINDLE: usize = 1;

    w.comment(&format!("{} - generated by Filar {}", project.name, env!("CARGO_PKG_VERSION")));
    w.comment(&format!("Machine: {}", m.name));
    w.comment(&format!(
        "Mandrel: {} x {} mm dia, {} mm long; part zone {} to {} mm",
        num(project.mandrel.start_diameter, 2),
        num(project.mandrel.end_diameter, 2),
        num(plan.mandrel.length, 1),
        num(plan.mandrel.part_start, 1),
        num(plan.mandrel.part_end, 1),
    ));
    let round = project.material.shape == crate::project::Shape::Round;
    w.comment(&format!(
        "{}: {} mm {}, {} | length {} m | est. time {}",
        if round { "Strand" } else { "Band" },
        num(if round { project.material.diameter() } else { project.material.band_width }, 2),
        if round { "dia" } else { "wide" },
        ascii(&project.material.name),
        num(plan.totals.fiber_length_m, 1),
        fmt_duration(plan.totals.duration)
    ));
    let mut axis_note = String::from("Axes:");
    for (ax, label) in axes.iter().zip(["carriage", "spindle", "cross-feed", "eye"]) {
        if ax.enabled {
            let _ = write!(axis_note, " {}={}", ax.letter, label);
        }
    }
    w.comment(&axis_note);

    if plan.blocks.is_empty() {
        w.comment("Nothing to wind.");
        return finish(w, 0, 0.0);
    }

    w.verbatim(&g.header);

    // Physical axis values of a sample, spindle in degrees from program start.
    let first = &plan.blocks[0].samples;
    let a0 = first.a[0];
    let physical = |s: &crate::plan::Samples, i: usize, turn: f64| -> [f64; 4] {
        [s.x[i], (s.a[i] + turn - a0).to_degrees(), s.y[i], s.b[i].to_degrees()]
    };

    // Go to the start pose, then zero the spindle there.
    let start = physical(first, 0, 0.0);
    let mut spindle_shift = 0.0; // degrees subtracted by G92 wraps so far
    let mut last = [0.0f64; 4];
    let mut line = String::from("G0");
    for i in 0..4 {
        last[i] = quantise(axes[i].to_machine(start[i]), dec);
        if axes[i].enabled && i != SPINDLE {
            let _ = write!(line, " {}{}", axes[i].letter, num(last[i], dec));
        }
    }
    w.comment("Move to the start position, then tie the fibre on");
    w.code(&line);
    w.code(&format!("G92 {}{}", axes[SPINDLE].letter, num(last[SPINDLE], dec)));
    w.code(match g.feed_mode {
        FeedMode::InverseTime => "G93",
        _ => "G94",
    });

    let mut moves = 0usize;
    let mut last_f = String::new();
    let mut carry_dt = 0.0;
    let mut last_layer = usize::MAX;

    for block in &plan.blocks {
        let s = &block.samples;
        if block.layer_index != last_layer {
            last_layer = block.layer_index;
            let layer = &project.layers[block.layer_index];
            let report = plan.layers.iter().find(|l| l.id == layer.id);
            let what = match &layer.kind {
                LayerKind::Helical { angle_deg, .. } => {
                    let n = report.map(|r| r.circuits).unwrap_or(0);
                    let p = report.and_then(|r| r.pattern.as_ref()).map(|p| p.pattern_number).unwrap_or(0);
                    format!("helical +/-{} deg, {} circuits, pattern {}", num(*angle_deg, 2), n, p)
                }
                LayerKind::Hoop { plies } => format!("hoop, {plies} pass(es)"),
            };
            w.comment(&format!("=== Layer {}: {} ({}) ===", block.layer_index + 1, ascii(&layer.name), what));
        }
        if block.kind == BlockKind::Link {
            w.comment("Link to layer start");
        }

        for rep in 0..block.repeats {
            let turn = block.phi_step * rep as f64;
            if block.kind == BlockKind::Helical {
                w.comment(&format!("Circuit {}/{}", rep + 1, block.repeats));
            }
            if g.rotary_mode == RotaryMode::WrapEachCircuit && axes[SPINDLE].scale != 0.0 {
                // Fold the spindle position back into one turn.
                let cur_phys = physical(s, 0, turn)[SPINDLE] - spindle_shift;
                let wrapped = cur_phys.rem_euclid(360.0);
                if (cur_phys - wrapped).abs() > 1e-9 {
                    spindle_shift += cur_phys - wrapped;
                    last[SPINDLE] = quantise(axes[SPINDLE].to_machine(wrapped), dec);
                    w.code(&format!("G92 {}{}", axes[SPINDLE].letter, num(last[SPINDLE], dec)));
                }
            }

            let mut prev = physical(s, 0, turn);
            prev[SPINDLE] -= spindle_shift;
            for i in 1..s.len() {
                let mut end = physical(s, i, turn);
                end[SPINDLE] -= spindle_shift;
                let t_base = block.t_start + block.duration * rep as f64;
                let span = s.t[i] - s.t[i - 1];
                // Long moves are cut into equal pieces so the controller (and
                // anyone pausing the job) never commits to minutes at a time.
                let pieces = if g.max_move_time > 0.0 {
                    ((span / g.max_move_time).ceil() as usize).clamp(1, 100_000)
                } else {
                    1
                };
                for piece in 1..=pieces {
                    let u = piece as f64 / pieces as f64;
                    let dt = span / pieces as f64 + carry_dt;
                    w.now = t_base + s.t[i - 1] + span * u;
                    let mut line = String::from("G1");
                    let mut lin2 = 0.0;
                    let mut rot2 = 0.0;
                    let mut target = last;
                    for k in 0..4 {
                        if !axes[k].enabled {
                            continue;
                        }
                        let phys = prev[k] + (end[k] - prev[k]) * u;
                        let v = quantise(axes[k].to_machine(phys), dec);
                        let d = v - last[k];
                        if d.abs() > 0.0 {
                            let _ = write!(line, " {}{}", axes[k].letter, num(v, dec));
                            if is_linear[k] {
                                lin2 += d * d;
                            } else {
                                rot2 += d * d;
                            }
                            target[k] = v;
                        }
                    }
                    if lin2 == 0.0 && rot2 == 0.0 {
                        // Below output resolution: fold the time into the next move.
                        carry_dt = dt;
                        continue;
                    }
                    carry_dt = 0.0;
                    last = target;
                    let minutes = dt / 60.0;
                    let f = match g.feed_mode {
                        FeedMode::InverseTime => num(1.0 / minutes, 4),
                        FeedMode::AllAxes => num((lin2 + rot2).sqrt() / minutes, 2),
                        FeedMode::LinearAxes => {
                            let d = if lin2 > 0.0 { lin2.sqrt() } else { rot2.sqrt() };
                            num(d / minutes, 2)
                        }
                    };
                    if g.feed_mode == FeedMode::InverseTime || f != last_f {
                        let _ = write!(line, " F{f}");
                        last_f = f;
                    }
                    w.code(&line);
                    moves += 1;
                }
                prev = end;
            }
        }
    }

    w.comment("=== End of winding ===");
    if g.feed_mode == FeedMode::InverseTime && !g.footer.contains("G94") {
        w.code("G94");
    }
    w.verbatim(&g.footer);
    finish(w, moves, plan.totals.duration)
}

fn ascii(s: &str) -> String {
    s.chars()
        .map(|c| match c {
            '±' => "+/-".to_string(),
            '°' => " deg".to_string(),
            c if c.is_ascii() => c.to_string(),
            _ => "?".to_string(),
        })
        .collect()
}

fn finish(w: Writer, moves: usize, duration: f64) -> Gcode {
    Gcode { lines: w.times.len(), moves, duration, line_times: w.times, text: w.text }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::machine::MachineProfile;
    use crate::plan::plan;
    use std::collections::HashMap;

    /// A tiny interpreter for the subset of G-code we emit. Returns the final
    /// axis positions (machine units, G92 offsets undone for the spindle) and
    /// the total time implied by the feed words.
    fn run(text: &str, mode: FeedMode, linear: &[char], spindle: char) -> (HashMap<char, f64>, f64, usize) {
        let mut pos: HashMap<char, f64> = HashMap::new();
        let mut spindle_unwrapped = 0.0;
        let mut f = 0.0;
        let mut time = 0.0;
        let mut moves = 0;
        for raw in text.lines() {
            let line = raw.split(';').next().unwrap().trim();
            if line.is_empty() || line.starts_with('(') {
                continue;
            }
            let words: Vec<&str> = line.split_whitespace().filter(|w| !w.starts_with('N')).collect();
            let cmd = words[0];
            let args: Vec<(char, f64)> = words[1..]
                .iter()
                .filter_map(|w| {
                    let c = w.chars().next()?;
                    w[1..].parse::<f64>().ok().map(|v| (c, v))
                })
                .collect();
            match cmd {
                "G92" => {
                    for (c, v) in args {
                        pos.insert(c, v);
                    }
                }
                "G0" => {
                    for (c, v) in args {
                        pos.insert(c, v);
                    }
                }
                "G1" => {
                    let mut lin2 = 0.0;
                    let mut rot2 = 0.0;
                    for (c, v) in &args {
                        if *c == 'F' {
                            f = *v;
                            continue;
                        }
                        let d = v - pos.get(c).copied().unwrap_or(0.0);
                        if linear.contains(c) {
                            lin2 += d * d;
                        } else {
                            rot2 += d * d;
                        }
                        if *c == spindle {
                            spindle_unwrapped += d;
                        }
                        pos.insert(*c, *v);
                    }
                    time += match mode {
                        FeedMode::InverseTime => 60.0 / f,
                        FeedMode::AllAxes => (lin2 + rot2).sqrt() / f * 60.0,
                        FeedMode::LinearAxes => {
                            (if lin2 > 0.0 { lin2.sqrt() } else { rot2.sqrt() }) / f * 60.0
                        }
                    };
                    moves += 1;
                }
                _ => {}
            }
        }
        pos.insert('@', spindle_unwrapped);
        (pos, time, moves)
    }

    fn check(mut project: Project, machine: MachineProfile, linear: &[char], spindle: char) {
        project.machine = machine;
        let plan = plan(&project);
        assert!(plan.warnings.iter().all(|w| w.level != crate::plan::Level::Error), "{:?}", plan.warnings);
        let g = generate(&project, &plan);
        assert_eq!(g.lines, g.text.lines().count());
        assert_eq!(g.lines, g.line_times.len());
        let (pos, time, moves) = run(&g.text, project.machine.gcode.feed_mode, linear, spindle);
        assert_eq!(moves, g.moves);
        // The feed words must reproduce the planned duration.
        assert!(
            (time / plan.totals.duration - 1.0).abs() < 2e-3,
            "{}: g-code runs {time:.1}s, plan {:.1}s",
            project.machine.name,
            plan.totals.duration
        );
        // The spindle must turn exactly as far as the plan says.
        let first = &plan.blocks[0].samples;
        let last_block = plan.blocks.last().unwrap();
        let ls = &last_block.samples;
        let end_a = ls.a[ls.len() - 1] + last_block.phi_step * (last_block.repeats as f64 - 1.0);
        let turned = (end_a - first.a[0]).to_degrees();
        assert!((pos[&'@'] - turned).abs() < 0.05, "spindle {} vs {}", pos[&'@'], turned);
        // And the carriage ends where the last sample is.
        let x = project.machine.carriage.letter.chars().next().unwrap();
        assert!((pos[&x] - ls.x[ls.len() - 1]).abs() < 2e-3);
        // Times are monotonic and end at the total.
        assert!(g.line_times.windows(2).all(|w| w[1] >= w[0]));
        assert!((*g.line_times.last().unwrap() as f64 - plan.totals.duration).abs() < 0.01);
    }

    #[test]
    fn every_preset_reproduces_the_plan() {
        for project in [Project::example_tube(), Project::example_cone()] {
            for machine in MachineProfile::presets() {
                let mut linear = vec![machine.carriage.letter.chars().next().unwrap()];
                if machine.crossfeed.enabled {
                    linear.push(machine.crossfeed.letter.chars().next().unwrap());
                }
                let spindle = machine.spindle.letter.chars().next().unwrap();
                check(project.clone(), machine, &linear, spindle);
            }
        }
    }

    #[test]
    fn wrapped_spindle_stays_within_a_circuit() {
        let mut project = Project::example_tube();
        project.machine = MachineProfile::marlin_xyz();
        let plan = plan(&project);
        let g = generate(&project, &plan);
        let biggest = plan
            .blocks
            .iter()
            .map(|b| {
                let s = &b.samples;
                (s.a[s.len() - 1] - s.a[0]).to_degrees()
            })
            .fold(0.0, f64::max);
        let letter = project.machine.spindle.letter.clone();
        for line in g.text.lines().filter(|l| l.starts_with("G1")) {
            for word in line.split_whitespace().filter(|w| w.starts_with(letter.as_str())) {
                let v: f64 = word[1..].parse().unwrap();
                assert!(v <= biggest + 360.0 + 1.0, "{line}");
            }
        }
        assert!(g.text.matches("G92").count() > 5);
    }

    #[test]
    fn disabled_axes_are_not_written() {
        let mut project = Project::example_tube();
        project.machine = MachineProfile::generic_2_axis();
        let plan = plan(&project);
        let g = generate(&project, &plan);
        for line in g.text.lines().filter(|l| l.starts_with("G1") || l.starts_with("G0")) {
            assert!(!line.contains(" Y") && !line.contains(" B"), "{line}");
        }
    }

    #[test]
    fn scale_and_invert_apply() {
        let mut project = Project::example_tube();
        project.machine = MachineProfile::generic_2_axis();
        let base = generate(&project, &plan(&project));
        project.machine.spindle.scale = 1.0 / 360.0; // revolutions
        project.machine.spindle.invert = true;
        project.machine.gcode.decimals = 5;
        let revs = generate(&project, &plan(&project));
        let last_a = |t: &str| -> f64 {
            t.lines()
                .rev()
                .filter(|l| l.starts_with("G1"))
                .find_map(|l| l.split_whitespace().find(|w| w.starts_with('A')).map(|w| w[1..].parse().unwrap()))
                .unwrap()
        };
        assert!((last_a(&base.text) / 360.0 + last_a(&revs.text)).abs() < 1e-3);
    }

    #[test]
    fn number_formatting() {
        assert_eq!(num(12.5, 3), "12.5");
        assert_eq!(num(-0.0001, 3), "0");
        assert_eq!(num(100.0, 3), "100");
        assert_eq!(num(1.23456, 3), "1.235");
    }
}
